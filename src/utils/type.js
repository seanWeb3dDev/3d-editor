/** 风门状态 */
export const DamperState = (value, state) => {
  if (state == 1) {
    return "- -";
  }
  switch (value) {
    case 0:
      return "未关到位";
    case 1:
      return "关闭中";
    case 2:
      return "关";
    case 8:
      return "未开到位";
    case 9:
      return "打开中";
    case 10:
      return "开";
    default:
      return "- -";
  }
};

/** 获取控制器模式 */
export const LocalizerType = (value) => {
  const types = ["未知控制器", "风门控制器", "风窗控制器", "测风站控制器"];
  return types[value + 1];
};
