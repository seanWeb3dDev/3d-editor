/** 传感器类型转换为地图 */
export const sensorTypeToMap = (typeList) => {
  const res = [];
  typeList.forEach((type) => {
    // 二氧化碳—101
    if (type == SensorType.Carbon_dioxide_sensor.value) {
      !res.includes(101) && res.push(101);
    }
    // 粉尘—102
    if (type == SensorType.Dust_sensors.value) {
      !res.includes(102) && res.push(102);
    }
    // 氧气—103
    if ([SensorType.Oxygen_sensor.value, SensorType.Pipe_oxygen_sensors.value].includes(type)) {
      !res.includes(103) && res.push(103);
    }
    // 温湿度—104
    if ([SensorType.Temperature_humidity_sensor.value].includes(type)) {
      !res.includes(104) && res.push(104);
    }
    // 声光—105
    if ([SensorType.Alarm_sensor.value].includes(type)) {
      !res.includes(105) && res.push(105);
    }
    // 差压—106
    if ([SensorType.Differential_pressure_sensor.value].includes(type)) {
      !res.includes(106) && res.push(106);
    }
    // 风速传感器—107
    if (SpeedSensorType.includes(type)) {
      !res.includes(107) && res.push(107);
    }
    // 一氧化碳—108
    if (COSensorType.includes(type)) {
      !res.includes(108) && res.push(108);
    }
    // 甲烷—109
    if (MethaneSensorType.includes(type)) {
      !res.includes(109) && res.push(109);
    }
    // 负压—110
    if (
      [
        SensorType.SmallRange_Negative_pressure_sensor.value,
        SensorType.Pipeline_pressure_sensor.value,
        SensorType.Negative_pressure_sensor.value,
      ].includes(type)
    ) {
      !res.includes(110) && res.push(110);
    }
  });
  return res;
};

