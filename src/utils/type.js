export const DeviceAlarm = () => {
  const res = [];
  Object.keys(AlarmType).forEach((key) => {
    if (!ParamAlarm.includes(AlarmType[key].value) && !ServerAlarm.includes(AlarmType[key].value)) {
      res.push(AlarmType[key].value);
    }
  });
  return res;
};

